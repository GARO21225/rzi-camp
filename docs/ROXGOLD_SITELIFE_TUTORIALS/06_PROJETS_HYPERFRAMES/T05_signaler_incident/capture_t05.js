const { chromium, devices } = require('playwright');
const path = require('path');
const { T, L, dossier, locale, lancement, initScript, textesNonTraduits } = require(path.join(__dirname, '..', '_commun', 'langue_capture.js'));
const OUT = dossier(__dirname);
(async () => {
  const b = await chromium.launch(lancement);
  const ctx = await b.newContext({ ...devices['iPhone 13'], locale, permissions: ['notifications'] });
  await ctx.addInitScript(...initScript);
  const pg = await ctx.newPage();
  pg.on('pageerror', e => console.log('PAGEERR', e.message));
  const shot = async (n, w = 1200) => { await pg.waitForTimeout(w); await pg.screenshot({ path: OUT + n }); console.log('shot', n, pg.url()); (await textesNonTraduits(pg)).forEach(t => console.log('NT', t)); };
  await pg.goto('http://127.0.0.1:5173/login'); await pg.waitForLoadState('networkidle');
  await pg.locator('input:not([type="password"])').first().fill('demo.resident');
  await pg.fill('input[type="password"]', 'DemoSiteLife2026!');
  await pg.locator('input[type="password"]').press('Enter');
  await pg.waitForURL(u => !String(u).includes('/login'), { timeout: 20000 });
  await pg.waitForLoadState('networkidle'); await pg.waitForTimeout(7000);
  await shot('03_accueil.png', 500);
  await pg.locator('.tb-item', { hasText: T('Signaler') }).first().click();
  await pg.waitForLoadState('networkidle');
  await shot('04_maintenance_liste.png', 2500);
  await pg.locator(`button[aria-label="${T('Déclarer un incident')}"]`).last().click();
  await shot('05_formulaire_vide.png');
  await pg.fill(`input[placeholder="${T("Titre de l'incident...")}"]`, L('Climatiseur en panne', 'Air conditioner not working'));
  await shot('06_titre.png', 400);
  await pg.fill(`textarea[placeholder="${T('Décrivez le problème...')}"]`, L('Le climatiseur ne refroidit plus depuis ce matin. Il fait un bruit inhabituel.', 'The air conditioner has not been cooling since this morning. It makes an unusual noise.'));
  const selects = pg.locator('select');
  await selects.nth(0).selectOption('Climatisation');
  await selects.nth(1).selectOption('haute');
  await shot('07_description_categorie_priorite.png', 400);
  const res = pg.locator(`input[placeholder="${T('Choisir dans la liste ou saisir…')}"]`);
  await res.scrollIntoViewIfNeeded(); await res.click(); await res.fill('DEMO-A02');
  await pg.waitForTimeout(500);
  await pg.getByText(T('Fermer'), { exact: true }).first().click().catch(() => {});
  await pg.fill(`input[placeholder="${T('Ex: Bloc 3, Ch. 12')}"]`, L('Bloc DEMO A', 'DEMO Block A'));
  await pg.getByText(T('⏱️ SLA assigné automatiquement selon la priorité')).first().scrollIntoViewIfNeeded();
  await shot('08_lieu_et_envoi.png', 500);
  await pg.getByText(T("🔧 Déclarer l'incident")).click();
  await pg.waitForLoadState('networkidle');
  await shot('09_incident_declare.png', 2500);
  await pg.getByText(L('Climatiseur en panne', 'Air conditioner not working')).first().click();
  await shot('10_detail_incident.png', 1500);
  await b.close();
})();
