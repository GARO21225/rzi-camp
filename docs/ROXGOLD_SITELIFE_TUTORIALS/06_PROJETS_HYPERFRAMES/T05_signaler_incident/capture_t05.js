const { chromium, devices } = require('playwright');
const OUT = require('path').join(__dirname, 'captures') + '/';
// Instance de DÉMO locale uniquement (compte fictif créé par seed_demo.py) — jamais la production.
(async () => {
  const b = await chromium.launch();
  const ctx = await b.newContext({ ...devices['iPhone 13'], locale: 'fr-FR', permissions: ['notifications'] });
  await ctx.addInitScript(() => { try { sessionStorage.setItem('pwa-dismissed','1'); localStorage.setItem('rzi_push_masque', String(Date.now()+9e9)) } catch {} });
  const pg = await ctx.newPage();
  pg.on('pageerror', e => console.log('PAGEERR', e.message));
  const shot = async (n, w=1200) => { await pg.waitForTimeout(w); await pg.screenshot({ path: OUT + n }); console.log('shot', n, pg.url()); };
  await pg.goto('http://127.0.0.1:5173/login'); await pg.waitForLoadState('networkidle');
  await pg.fill('input[placeholder="Votre identifiant"], input[placeholder="Identifiant de connexion"]', 'demo.resident');
  await pg.fill('input[type="password"]', 'DemoSiteLife2026!');
  await pg.getByText('Se connecter →').first().click();
  await pg.waitForURL(u => !String(u).includes('/login'), { timeout: 20000 });
  await pg.waitForLoadState('networkidle'); await pg.waitForTimeout(7000);
  await shot('03_accueil.png', 500);
  await pg.locator('.tb-item', { hasText: 'Signaler' }).first().click();
  await pg.waitForLoadState('networkidle');
  await shot('04_maintenance_liste.png', 2500);
  await pg.locator('button[aria-label="Déclarer un incident"]').last().click();
  await shot('05_formulaire_vide.png');
  await pg.fill('input[placeholder^="Titre de l"]', 'Climatiseur en panne');
  await shot('06_titre.png', 400);
  await pg.fill('textarea[placeholder="Décrivez le problème..."]', 'Le climatiseur ne refroidit plus depuis ce matin. Il fait un bruit inhabituel.');
  const selects = pg.locator('select');
  await selects.nth(0).selectOption('Climatisation');
  await selects.nth(1).selectOption('haute');
  await shot('07_description_categorie_priorite.png', 400);
  const res = pg.locator('input[placeholder="Choisir dans la liste ou saisir…"]');
  await res.scrollIntoViewIfNeeded(); await res.click(); await res.fill('DEMO-A02');
  await pg.waitForTimeout(500);
  await pg.getByText('Fermer', { exact: true }).first().click().catch(()=>{});
  await pg.fill('input[placeholder="Ex: Bloc 3, Ch. 12"]', 'Bloc DEMO A');
  await pg.locator('text=SLA assigné automatiquement').scrollIntoViewIfNeeded();
  await shot('08_lieu_et_envoi.png', 500);
  await pg.getByText("🔧 Déclarer l'incident").click();
  await pg.waitForLoadState('networkidle');
  await shot('09_incident_declare.png', 2500);
  await pg.getByText('Climatiseur en panne').first().click();
  await shot('10_detail_incident.png', 1500);
  await b.close();
})();
